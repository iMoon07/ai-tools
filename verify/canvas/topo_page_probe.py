import json, subprocess, time, urllib.parse, urllib.request, shutil

PORT = 9471
PROF = "/tmp/alur-probes/prof-topo-page"
shutil.rmtree(PROF, ignore_errors=True)
proc = subprocess.Popen(["chromium", "--headless=new", f"--remote-debugging-port={PORT}",
    f"--user-data-dir={PROF}", "--no-first-run", "--no-default-browser-check",
    "--disable-gpu", "--window-size=1400,1000", "--remote-allow-origins=*", "about:blank"],
    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
import websocket

def http(p, method="GET"):
    return json.loads(urllib.request.urlopen(
        urllib.request.Request(f"http://127.0.0.1:{PORT}{p}", method=method), timeout=10).read())

for _ in range(80):
    try: http("/json/version"); break
    except Exception: time.sleep(0.3)

def newtab():
    t = http("/json/new?" + urllib.parse.quote("about:blank", safe=""), method="PUT")
    ws = websocket.create_connection(t["webSocketDebuggerUrl"], timeout=60, suppress_origin=True)
    n = [0]
    def send(m, **p):
        n[0] += 1
        ws.send(json.dumps({"id": n[0], "method": m, "params": p}))
        while True:
            r = json.loads(ws.recv())
            if r.get("id") == n[0]:
                if r.get("method") == "Runtime.exceptionThrown":
                    print("   [exception]", r["params"]["exceptionDetails"].get("text"))
                if r.get("method") == "Runtime.consoleAPICalled":
                    a = r["params"]["args"]
                    print("   [console]", " ".join(str(x.get("value", x.get("description"))) for x in a))
                if r.get("error"): raise RuntimeError(r["error"])
                return r.get("result", {})
    return ws, send

def run(width, height, label):
    ws, send = newtab()
    send("Runtime.enable"); send("Page.enable")
    send("Emulation.setDeviceMetricsOverride", width=width, height=height, deviceScaleFactor=1, mobile=width < 700)
    send("Page.navigate", url="http://127.0.0.1:8123/topology.html")
    time.sleep(4)
    print(f"== {label} ({width}x{height}) ==")

    def ev(e):
        r = send("Runtime.evaluate", expression=e, returnByValue=True)
        res = r.get("result", {})
        if res.get("subtype") == "error":
            return "ERR " + str(res.get("description"))[:160]
        return res.get("value")

    print("  render:", ev("""JSON.stringify({
      nodes: document.querySelectorAll('#preview .topo-node').length,
      paths: document.querySelectorAll('#preview path').length,
      title: document.querySelector('#preview .topo-title, #preview .topo-caption') ? true : false,
      facilities: document.querySelectorAll('#preview .topo-facility').length,
      previewBg: getComputedStyle(document.getElementById('preview')).backgroundColor,
      specChars: document.getElementById('specBox').value.length
    })"""))

    print("  logo tiles:", ev("document.querySelectorAll('#logoGrid .logo-tile').length"))
    print("  preset buttons:", ev("document.querySelectorAll('#presetGrid [data-preset]').length"))

    # click a node on canvas -> should select it in the panel
    print("  select node:", ev("""(()=>{const n=document.querySelectorAll('#preview .topo-node')[1];
      n.dispatchEvent(new MouseEvent('click',{bubbles:true}));
      return JSON.stringify({sel:[...document.querySelectorAll('#nodeList .card.is-on b')].map(b=>b.textContent)});})()"""))

    # change label of the selected node through the first input
    print("  rename:", ev("""(()=>{const card=document.querySelector('#nodeList .card.is-on');
      const input=card && card.querySelector('input[type=text]');
      if(!input) return 'no input';
      input.value='Renamed waiter';
      input.dispatchEvent(new Event('input',{bubbles:true}));
      return document.querySelectorAll('#preview .topo-node')[1].textContent.slice(0,30);})()"""))

    # copy fence content (read the textarea generated by the export path)
    fence = ev("""(()=>{const b=document.getElementById('copyBtn');
      return typeof navigator.clipboard; })()""")
    print("  clipboard api:", fence)
    print("  fence preview:", ev("""(()=>{const v=document.getElementById('specBox').value;
      return '```topology\\n'+v.slice(0,60)+'\\n...';})()"""))

    print("  guides toggle:", ev("""(()=>{const b=document.getElementById('guidesBtn');b.click();
      return JSON.stringify({cls:document.getElementById('stage').className,
        bg:getComputedStyle(document.getElementById('stage')).backgroundImage.slice(0,30),
        label:b.textContent});})()"""))

    ws.close()

run(1400, 1000, "desktop")
run(390, 844, "mobile")
proc.terminate()