#!/usr/bin/env python3
"""Build the Alur logo manifest for the remote iMoon07/logo-svg library.

Reads every SVG/PNG under the four logo categories from a local checkout and
writes the site's synchronous manifest:

  * js/logo-manifest.js  (window.ALUR_LOGO_MANIFEST)

The manifest points at raw.githubusercontent.com; the site does not ship the
logo files. Each entry is "<category>:<name>". Single-colour dark logos get
`dark: true` so the renderer can put a light tile behind them.

Usage:
  python3 ai-tools/tools/build_logo_manifest.py --site /home/moon/Projects/imoon07.github.io
  python3 ai-tools/tools/build_logo_manifest.py --logo-dir /home/moon/Projects/logo
"""
import argparse
import json
import re
from pathlib import Path

DEFAULT_SITE = Path("/home/moon/Projects/imoon07.github.io")
DEFAULT_LOGO = Path("/home/moon/Projects/logo")
REMOTE_BASE = "https://raw.githubusercontent.com/iMoon07/logo-svg/main/"
# "motion" holds the animated SMIL set (build_motion.py); it rides the same
# remote path as the static logos.
CATEGORIES = ("profession", "programming", "security", "stack", "motion")

FILL = re.compile(r'(?:fill|stroke)\s*[:=]\s*["\']?(#[0-9a-fA-F]{3,8}|[a-zA-Z]+)')
HEX = re.compile(r'^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$')
NAMED = {
    "black": "#000000", "white": "#ffffff", "none": None, "transparent": None,
    "currentcolor": None, "inherit": None,
}
DARK_THRESHOLD = 0.34


def rgb(value):
    value = value.strip()
    if value.lower() in NAMED:
        return None if NAMED[value.lower()] is None else _hex_rgb(NAMED[value.lower()])
    if HEX.match(value):
        return _hex_rgb(value)
    return None


def _hex_rgb(value):
    h = value.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def luma(rgb):
    def lin(c):
        c /= 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def is_dark(path):
    """True when every explicit fill/stroke colour is dark, or when the file
    declares no colour at all (SVG defaults to black)."""
    if path.suffix.lower() in (".png", ".webp", ".gif"):
        return False
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return True
    # Ignore the outer <svg> element's own fill/stroke (usually none/currentColor).
    inner = re.sub(r'^.*?<svg\b[^>]*>', '', text, count=1, flags=re.S)
    colours = []
    for token in FILL.findall(inner):
        value = token.strip()
        if value.startswith("url(") or value.lower() in ("none", "transparent"):
            continue
        got = rgb(value)
        if got is not None:
            colours.append(got)
    if not colours:
        return True
    return all(luma(c) < DARK_THRESHOLD for c in colours)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", default=str(DEFAULT_SITE))
    ap.add_argument("--logo-dir", default=str(DEFAULT_LOGO))
    args = ap.parse_args()
    root = Path(args.logo_dir)
    site = Path(args.site)
    out_js = site / "js" / "logo-manifest.js"

    entries = []
    for cat in CATEGORIES:
        folder = root / cat
        if not folder.is_dir():
            continue
        for path in sorted(folder.iterdir()):
            if not path.is_file() or path.suffix.lower() not in (".svg", ".png", ".webp", ".gif"):
                continue
            name = path.stem
            entries.append({
                "id": "%s:%s" % (cat, name),
                "name": name,
                "category": cat,
                "file": "%s/%s" % (cat, path.name),
                "ext": path.suffix.lower().lstrip("."),
                "dark": is_dark(path),
                "search": ("%s %s" % (name, cat)).lower(),
            })

    brand_dir = site / "assets" / "brands"
    brand_entries = []
    if brand_dir.is_dir():
        for path in sorted(brand_dir.iterdir()):
            if not path.is_file() or path.suffix.lower() != ".svg":
                continue
            name = path.stem
            brand_entries.append({
                "id": "brand:%s" % name,
                "name": name,
                "category": "brand",
                "file": "assets/brands/%s" % path.name,
                "url": "assets/brands/%s" % path.name,
                "ext": "svg",
                "dark": is_dark(path),
                "search": ("%s brand" % name).lower(),
            })
    entries.extend(brand_entries)

    entries.sort(key=lambda e: (e["name"], e["category"]))
    categories = list(CATEGORIES) + (["brand"] if brand_entries else [])
    data = {
        "base": REMOTE_BASE,
        "source": "iMoon07/logo-svg",
        "categories": categories,
        "logos": entries,
    }

    out_js.parent.mkdir(parents=True, exist_ok=True)
    out_js.write_text(
        "/* Logo manifest: iMoon07/logo-svg (remote GitHub). Generated by "
        "ai-tools/tools/build_logo_manifest.py — do not edit by hand. */\n"
        "window.ALUR_LOGO_MANIFEST = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    dark = sum(1 for e in entries if e["dark"])
    print("logos:", len(entries), "dark:", dark, "->", out_js)


if __name__ == "__main__":
    main()