#!/usr/bin/env python3
"""Add the animated logo set (logo/motion) to the site logo manifest.

The manifest is generated by build_logo_manifest.py, but the copy on the site
also carries the icon/3D/illustration categories that the generator no longer
scans. Regenerating would drop them, so this script patches the existing
manifest in place: it appends one entry per motion SVG and adds the category.

  python3 ai-tools/generators/add_motion_logos.py \
      --site /home/moon/Projects/imoon07.github.io \
      --logo-dir /home/moon/Projects/logo
"""
import argparse
import json
import re
from pathlib import Path

DEFAULT_SITE = Path("/home/moon/Projects/imoon07.github.io")
DEFAULT_LOGO = Path("/home/moon/Projects/logo")
CATEGORY = "motion"
MANIFEST_RE = re.compile(r"^(/\*.*?\*/\nwindow\.ALUR_LOGO_MANIFEST = )(\{.*\});$", re.S)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", default=str(DEFAULT_SITE))
    ap.add_argument("--logo-dir", default=str(DEFAULT_LOGO))
    args = ap.parse_args()
    site = Path(args.site)
    folder = Path(args.logo_dir) / CATEGORY
    out_js = site / "js" / "logo-manifest.js"

    text = out_js.read_text(encoding="utf-8")
    hit = MANIFEST_RE.match(text)
    if not hit:
        raise SystemExit("manifest header/format not recognised: %s" % out_js)
    data = json.loads(hit.group(2))

    entries = []
    for path in sorted(folder.glob("*.svg")):
        entries.append({
            "id": "%s:%s" % (CATEGORY, path.stem),
            "name": path.stem,
            "category": CATEGORY,
            "file": "%s/%s" % (CATEGORY, path.name),
            "ext": "svg",
            "dark": False,
            "search": ("%s %s animated motion" % (path.stem, CATEGORY)).lower(),
            "motion": True,
        })

    logos = [e for e in data["logos"] if e.get("category") != CATEGORY]
    logos.extend(entries)
    logos.sort(key=lambda e: (e["name"], e["category"]))
    data["logos"] = logos
    cats = [c for c in data.get("categories", []) if c != CATEGORY]
    if cats and cats[-1] == "brand":
        cats.insert(-1, CATEGORY)
    else:
        cats.append(CATEGORY)
    data["categories"] = cats

    out_js.write_text(
        hit.group(1) + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print("logos:", len(logos), "motion:", len(entries), "->", out_js)


if __name__ == "__main__":
    main()